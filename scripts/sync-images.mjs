#!/usr/bin/env node
// Scans assets/images/exercises/<id>_a.jpg (+ optional <id>_b.jpg) and writes src/data/images.generated.ts
// with static require() calls (Metro only bundles assets referenced by literal require paths).
//   _a = start of the rep (or the held position), _b = the other end of the movement.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'images', 'exercises');
if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
const out = join(root, 'src', 'data', 'images.generated.ts');

const files = new Set(readdirSync(dir).filter((f) => /\.(jpg|png)$/.test(f)));
const ids = [...new Set([...files].map((f) => f.match(/^([a-z0-9-]+)_a\.(jpg|png)$/)?.[1]).filter(Boolean))].sort();
const req = (f) => `require('../../assets/images/exercises/${f}')`;
const entries = ids.map((id) => {
  const a = [...files].find((f) => f.startsWith(`${id}_a.`));
  const b = [...files].find((f) => f.startsWith(`${id}_b.`));
  return `  '${id}': { a: ${req(a)}${b ? `, b: ${req(b)}` : ''} },`;
});

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/sync-images.mjs. Do not edit by hand.\n` +
    `export const EXERCISE_IMAGES: Record<string, { a: number; b?: number }> = {\n` +
    entries.join('\n') + (entries.length ? '\n' : '') + `};\n`,
);
console.log(`images.generated.ts: ${entries.length} exercise(s) with images`);
