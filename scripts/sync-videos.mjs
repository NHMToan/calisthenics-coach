#!/usr/bin/env node
// Scans assets/videos/*.mp4 and writes src/data/videos.generated.ts with static require() calls
// (Metro can only bundle assets referenced by literal require paths).
//
// Optional per-clip rep count: name the file `<id>.<reps>x.mp4`, e.g. `squat.2x.mp4`.
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets', 'videos');
const out = join(root, 'src', 'data', 'videos.generated.ts');

const files = readdirSync(dir).filter((f) => f.endsWith('.mp4')).sort();
const entries = files.map((f) => {
  const m = f.match(/^([a-z0-9-]+)(?:\.(\d+)x)?\.mp4$/);
  if (!m) throw new Error(`Bad video file name: ${f} (expected <exercise-id>.mp4 or <exercise-id>.<reps>x.mp4)`);
  return `  '${m[1]}': { source: require('../../assets/videos/${f}'), repsPerLoop: ${m[2] ?? 1} },`;
});

writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/sync-videos.mjs. Do not edit by hand.\n` +
    `export const LOCAL_VIDEOS: Record<string, { source: number; repsPerLoop: number }> = {\n` +
    entries.join('\n') +
    (entries.length ? '\n' : '') +
    `};\n`,
);
console.log(`videos.generated.ts: ${entries.length} video(s)`);
